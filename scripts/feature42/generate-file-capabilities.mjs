#!/usr/bin/env node
/* global console, process */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const root = resolve(import.meta.dirname, "../..");
const defaultManifest = resolve(root, "contracts/file-capabilities.v1.json");
const tsOutput = resolve(root, "src/shared/fileCapabilities.generated.ts");
const rustOutput = resolve(root, "src-tauri/src/file_capabilities_generated.rs");
const argument = (name) => { const index = process.argv.indexOf(name); return index >= 0 ? process.argv[index + 1] : undefined; };

function loadManifest(path) {
  const manifest = JSON.parse(readFileSync(path, "utf8"));
  if (manifest.version !== "file-capabilities.v1" || manifest.schemaVersion !== 1) throw new Error("invalid file capability version");
  if (!Array.isArray(manifest.capabilities) || manifest.capabilities.length !== 2) throw new Error("capabilities must contain markdown and text-source only");
  const kinds = new Set(["markdown", "text-source"]);
  const extensions = new Set();
  let markdownOwners = 0;
  for (const capability of manifest.capabilities) {
    if (!kinds.has(capability.kind) || !Array.isArray(capability.extensions)) throw new Error("unknown capability kind or extensions");
    if (capability.kind === "markdown") markdownOwners += 1;
    for (const extension of capability.extensions) {
      if (extension !== extension.toLowerCase() || extension.length === 0 || !/^[a-z0-9]+$/.test(extension)) throw new Error(`invalid extension: ${extension}`);
      if (extensions.has(extension)) throw new Error(`duplicate extension: ${extension}`);
      extensions.add(extension);
    }
  }
  if (markdownOwners !== 1) throw new Error("exactly one markdown capability owner is required");
  const markdown = manifest.capabilities.find((item) => item.kind === "markdown");
  const text = manifest.capabilities.find((item) => item.kind === "text-source");
  if (JSON.stringify(markdown.extensions) !== JSON.stringify(["md", "markdown"])) throw new Error("markdown extensions must be md/markdown");
  if (!text.extensions.includes("json") || !text.extensions.includes("txt")) throw new Error("text-source allowlist is incomplete");
  if (manifest.directories?.visible !== true) throw new Error("directories must remain visible");
  return manifest;
}

function renderTypeScript(manifest) {
  const capabilities = JSON.stringify(manifest.capabilities, null, 2);
  return `// Generated by scripts/feature42/generate-file-capabilities.mjs. Do not edit.\n\nexport const FILE_CAPABILITIES_VERSION = ${JSON.stringify(manifest.version)} as const;\nexport const FILE_CAPABILITIES: readonly { readonly kind: "markdown" | "text-source"; readonly extensions: readonly string[] }[] = ${capabilities};\nexport type FileKind = typeof FILE_CAPABILITIES[number]["kind"];\nexport const FILE_PICKER_EXTENSIONS: readonly string[] = FILE_CAPABILITIES.flatMap((capability) => capability.extensions);\n\nexport function fileExtension(path: string): string {\n  const name = path.replace(/\\\\/g, "/").split("/").pop() ?? "";\n  const dot = name.lastIndexOf(".");\n  return dot > 0 ? name.slice(dot + 1).toLowerCase() : "";\n}\n\nexport function classifyFilePath(path: string): FileKind | null {\n  const extension = fileExtension(path);\n  for (const capability of FILE_CAPABILITIES) if (capability.extensions.includes(extension)) return capability.kind;\n  return null;\n}\n\nexport function isSupportedFilePath(path: string): boolean { return classifyFilePath(path) !== null; }\nexport function isMarkdownPath(path: string): boolean { return classifyFilePath(path) === "markdown"; }\n`;
}

function renderRust(manifest) {
  const markdown = manifest.capabilities.find((item) => item.kind === "markdown").extensions;
  const text = manifest.capabilities.find((item) => item.kind === "text-source").extensions;
  const match = (extensions, kind) => extensions.map((extension) => `        "${extension}" => Some(FileKind::${kind}),`).join("\n");
  const source = `// Generated by scripts/feature42/generate-file-capabilities.mjs. Do not edit.\n\n#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]\n#[serde(rename_all = "kebab-case")]\npub enum FileKind {\n    Markdown,\n    TextSource,\n}\n\npub const FILE_CAPABILITIES_VERSION: &str = ${JSON.stringify(manifest.version)};\npub const FILE_PICKER_EXTENSIONS: &[&str] = &[${[...markdown, ...text].map((extension) => `"${extension}"`).join(", ")}];\n\npub fn classify_extension(extension: &str) -> Option<FileKind> {\n    match extension.to_ascii_lowercase().as_str() {\n${match(markdown, "Markdown")}\n${match(text, "TextSource")}\n        _ => None,\n    }\n}\n\npub fn classify_path(path: &std::path::Path) -> Option<FileKind> {\n    path.extension().and_then(|extension| extension.to_str()).and_then(classify_extension)\n}\n`;
  return execFileSync("rustfmt", ["--emit", "stdout"], { input: source, encoding: "utf8" });
}

export function generate({ check = false, manifestPath = defaultManifest } = {}) {
  const manifest = loadManifest(manifestPath);
  const ts = renderTypeScript(manifest);
  const rust = renderRust(manifest);
  if (check) {
    if (!existsSync(tsOutput) || readFileSync(tsOutput, "utf8") !== ts) throw new Error(`stale generated TypeScript: ${tsOutput}`);
    if (!existsSync(rustOutput) || readFileSync(rustOutput, "utf8") !== rust) throw new Error(`stale generated Rust: ${rustOutput}`);
  } else {
    writeFileSync(tsOutput, ts, "utf8");
    writeFileSync(rustOutput, rust, "utf8");
  }
  return { status: "pass", check, version: manifest.version, kindCount: manifest.capabilities.length, extensionCount: manifest.capabilities.reduce((count, item) => count + item.extensions.length, 0) };
}

if (resolve(process.argv[1] ?? "") === resolve(fileURLToPath(import.meta.url))) {
  try { console.log(JSON.stringify(generate({ check: process.argv.includes("--check"), manifestPath: argument("--manifest") ? resolve(root, argument("--manifest")) : defaultManifest }), null, 2)); }
  catch (error) { console.error(`generate-file-capabilities failed: ${error instanceof Error ? error.message : String(error)}`); process.exitCode = 1; }
}
