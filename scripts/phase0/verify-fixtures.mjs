#!/usr/bin/env node
/* global console */
import { createHash } from 'node:crypto';
import { existsSync, lstatSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import process from 'node:process';

const workspaceRoot = resolve(import.meta.dirname, '../..');

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function parseArgs(argv) {
  const args = {};
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--left') args.left = argv[++index];
    else if (argv[index] === '--right') args.right = argv[++index];
    else if (argv[index] === '--manifest') args.manifest = argv[++index];
    else if (argv[index] === '--help') args.help = true;
    else throw new Error(`Unknown argument: ${argv[index]}`);
  }
  return args;
}

function filesUnder(root) {
  const files = [];
  function visit(directory) {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const absolute = join(directory, entry.name);
      if (entry.isSymbolicLink()) throw new Error(`Symlink/reparse fixture entry is not allowed: ${absolute}`);
      if (entry.isDirectory()) visit(absolute);
      else if (entry.isFile()) {
        files.push({ path: relative(root, absolute).replaceAll('\\', '/'), bytes: statSync(absolute).size, sha256: sha256(readFileSync(absolute)) });
      } else throw new Error(`Unsupported fixture entry type: ${absolute}`);
    }
  }
  if (!existsSync(root) || !lstatSync(root).isDirectory() || lstatSync(root).isSymbolicLink()) throw new Error(`Fixture root is not a normal directory: ${root}`);
  visit(root);
  return files.sort((left, right) => left.path.localeCompare(right.path));
}

function loadFixture(root, template) {
  const manifestPath = join(root, 'fixture-manifest.json');
  if (!existsSync(manifestPath)) throw new Error(`Missing generated manifest: ${manifestPath}`);
  const generated = JSON.parse(readFileSync(manifestPath, 'utf8'));
  if (generated.manifest_version !== template.manifest_version || generated.generator !== template.generator) throw new Error('Generated manifest version/generator mismatch');
  const profile = template.profiles[generated.profile];
  if (!profile) throw new Error(`Generated manifest has unknown profile: ${generated.profile}`);
  for (const [key, expected] of Object.entries(profile)) if (generated.profile_definition?.[key] !== expected) throw new Error(`Profile definition mismatch: ${key}`);
  const listed = generated.files;
  if (!Array.isArray(listed) || listed.some((file) => !file.path || file.path.includes('..') || file.path.startsWith('/'))) throw new Error('Generated manifest contains unsafe or invalid file paths');
  const actual = filesUnder(root).filter((file) => file.path !== 'fixture-manifest.json');
  const expected = [...listed].sort((left, right) => left.path.localeCompare(right.path));
  if (JSON.stringify(actual) !== JSON.stringify(expected)) throw new Error(`Generated file checksums do not match manifest in ${root}`);
  const contentRoot = sha256(expected.map((file) => `${file.path}\0${file.sha256}\n`).join(''));
  if (contentRoot !== generated.content_root_sha256) throw new Error(`Content root mismatch in ${root}`);
  if (generated.generated_bytes !== expected.reduce((total, file) => total + file.bytes, 0)) throw new Error(`Generated byte count mismatch in ${root}`);
  return { root, profile: generated.profile, seed: generated.seed, content_root_sha256: contentRoot, file_count: actual.length, generated_bytes: generated.generated_bytes, manifest_sha256: sha256(readFileSync(manifestPath)) };
}

try {
  const args = parseArgs(process.argv.slice(2));
  if (args.help || !args.left || !args.right || !args.manifest) {
    console.log('Usage: node scripts/phase0/verify-fixtures.mjs --left <fixture-dir> --right <fixture-dir> --manifest <manifest.json>');
    process.exit(args.help ? 0 : 2);
  }
  const template = JSON.parse(readFileSync(resolve(workspaceRoot, args.manifest), 'utf8'));
  const left = loadFixture(resolve(args.left), template);
  const right = loadFixture(resolve(args.right), template);
  if (left.profile !== right.profile || left.seed !== right.seed || left.content_root_sha256 !== right.content_root_sha256 || left.file_count !== right.file_count || left.generated_bytes !== right.generated_bytes || left.manifest_sha256 !== right.manifest_sha256) throw new Error('Independent fixture generations are not identical');
  console.log(JSON.stringify({ status: 'pass', left, right, exact_match: true }, null, 2));
} catch (error) {
  console.error(`verify-fixtures failed: ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
}
