#!/usr/bin/env node
/* global console */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import process from 'node:process';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const workspaceRoot = resolve(scriptDir, '../..');
const manifestPath = resolve(workspaceRoot, 'contracts/ipc.v1.json');
const tsOutputPath = resolve(workspaceRoot, 'src/shared/ipc/generated.ts');
const rustOutputPath = resolve(workspaceRoot, 'src-tauri/src/ipc/generated.rs');

function readManifest(path = manifestPath) {
  const manifest = JSON.parse(readFileSync(path, 'utf8'));
  validateManifest(manifest);
  return manifest;
}

function validateManifest(manifest) {
  if (manifest.version !== 'ipc.v1' || manifest.schemaVersion !== 1) {
    throw new Error('IPC manifest must declare ipc.v1/schemaVersion 1');
  }
  if (!Array.isArray(manifest.commands) || manifest.commands.length !== 39) {
    throw new Error(`IPC manifest must contain exactly 39 commands; got ${manifest.commands?.length ?? 0}`);
  }
  if (manifest.metadataCommands !== undefined && !Array.isArray(manifest.metadataCommands)) {
    throw new Error('metadataCommands must be an array when present');
  }
  if (!Array.isArray(manifest.events) || manifest.events.length !== 4) {
    throw new Error(`IPC manifest must contain exactly 4 events; got ${manifest.events?.length ?? 0}`);
  }
  const commandNames = new Set();
  for (const command of manifest.commands) {
    if (!command.name || !command.handler || !Array.isArray(command.args) || !command.result) {
      throw new Error(`Invalid command record: ${JSON.stringify(command)}`);
    }
    if (commandNames.has(command.name)) throw new Error(`Duplicate command: ${command.name}`);
    commandNames.add(command.name);
  }
  const eventNames = new Set();
  for (const event of manifest.events) {
    if (!event.name || !event.payload || eventNames.has(event.name)) {
      throw new Error(`Invalid or duplicate event record: ${JSON.stringify(event)}`);
    }
    eventNames.add(event.name);
  }
}

function renderTs(manifest) {
  const commands = manifest.commands.map((command) => ({ name: command.name, handler: command.handler, args: command.args, result: command.result }));
  const metadataCommands = manifest.metadataCommands ?? [];
  const events = manifest.events.map((event) => ({ name: event.name, payload: event.payload }));
  return `// Generated by scripts/ipc/generate-contracts.mjs. Do not edit.\n\nexport const IPC_VERSION = ${JSON.stringify(manifest.version)} as const;\n\nexport const IPC_COMMANDS = ${JSON.stringify(commands, null, 2)} as const;\nexport const IPC_METADATA_COMMANDS = ${JSON.stringify(metadataCommands, null, 2)} as const;\nexport type IpcCommandName = typeof IPC_COMMANDS[number]['name'];\nexport type IpcMetadataCommandName = typeof IPC_METADATA_COMMANDS[number]['name'];\n\nexport const IPC_EVENTS = ${JSON.stringify(events, null, 2)} as const;\nexport type IpcEventName = typeof IPC_EVENTS[number]['name'];\n\nexport const IPC_PLATFORM_OPERATIONS = ${JSON.stringify(manifest.platformOperations, null, 2)} as const;\nexport const IPC_ERROR_UNION = ${JSON.stringify(manifest.errors.union)} as const;\n`;
}

function renderRust(manifest) {
  const metadata = manifest.commands.map((command) => `    CommandMetadata {\n        name: ${JSON.stringify(command.name)},\n        handler: ${JSON.stringify(command.handler)},\n    },`).join('\n');
  const metadataCommands = manifest.metadataCommands ?? [];
  const additiveMetadata = metadataCommands.map((command) => `    CommandMetadata {\n        name: ${JSON.stringify(command.name)},\n        handler: ${JSON.stringify(command.handler)},\n    },`).join('\n');
  const handlers = [...manifest.commands, ...metadataCommands].map((command) => `            ${command.handler},`).join('\n');
  return `// Generated by scripts/ipc/generate-contracts.mjs. Do not edit.\n\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub struct CommandMetadata {\n    pub name: &'static str,\n    pub handler: &'static str,\n}\n\npub const IPC_VERSION: &str = ${JSON.stringify(manifest.version)};\npub const IPC_COMMANDS: &[CommandMetadata] = &[\n${metadata}\n];\npub const IPC_COMMAND_COUNT: usize = ${manifest.commands.length};\npub const IPC_METADATA_COMMANDS: &[CommandMetadata] = &[\n${additiveMetadata}\n];\n\n#[macro_export]\nmacro_rules! generated_ipc_handler {\n    () => {\n        tauri::generate_handler![\n${handlers}\n        ]\n    };\n}\n`;
}

function writeOrCheck(path, content, check) {
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      throw new Error(`Generated contract is stale: ${path}`);
    }
    return;
  }
  writeFileSync(path, content, 'utf8');
}

export function generate({ check = false, manifest = manifestPath } = {}) {
  const loaded = readManifest(manifest);
  writeOrCheck(tsOutputPath, renderTs(loaded), check);
  writeOrCheck(rustOutputPath, renderRust(loaded), check);
  return { status: 'pass', check, commandCount: loaded.commands.length, eventCount: loaded.events.length, outputs: [tsOutputPath, rustOutputPath] };
}

if (resolve(process.argv[1] ?? '') === resolve(fileURLToPath(import.meta.url))) {
  try {
    const check = process.argv.includes('--check');
    if (process.argv.some((arg) => arg.startsWith('--manifest='))) {
      const manifest = resolve(workspaceRoot, process.argv.find((arg) => arg.startsWith('--manifest=')).slice('--manifest='.length));
      console.log(JSON.stringify(generate({ check, manifest }), null, 2));
    } else {
      console.log(JSON.stringify(generate({ check }), null, 2));
    }
  } catch (error) {
    console.error(`generate-contracts failed: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  }
}
