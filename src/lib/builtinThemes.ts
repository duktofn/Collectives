const channels = (hex: string) =>
  [1, 3, 5].map((start) => parseInt(hex.slice(start, start + 2), 16));
const mix = (first: string, second: string, weight: number) => {
  const a = channels(first),
    b = channels(second);
  return (
    '#' +
    a
      .map((value, index) =>
        Math.round(value + (b[index] - value) * weight)
          .toString(16)
          .padStart(2, '0')
      )
      .join('')
  );
};
function luminance(hex: string) {
  const values = channels(hex).map((value) => {
    const c = value / 255;
    return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return values[0] * 0.2126 + values[1] * 0.7152 + values[2] * 0.0722;
}
function contrast(first: string, second: string) {
  const a = luminance(first),
    b = luminance(second);
  return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
}
function readable(color: string, backgrounds: string[], dark: boolean) {
  const target = dark ? '#ffffff' : '#000000';
  for (let step = 0; step <= 100; step++) {
    const adjusted = mix(color, target, step / 100);
    if (backgrounds.every((background) => contrast(adjusted, background) >= 4.5)) return adjusted;
  }
  return target;
}

